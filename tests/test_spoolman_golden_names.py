"""Shared golden test for Spoolman name shortening.

``tests/fixtures/spoolman_golden_names.json`` maps input records to the names expected
after ``shorten_long_names``. It is generated by running the reference implementation in
https://github.com/csmarshall/ofd-to-spoolman (``ofd2spoolman.shorten_long_names``) on the
inputs, and the same file is meant to be asserted there too, so the two projects cannot
drift apart. It MUST be regenerated from ofd-to-spoolman whenever that project's naming
rules change. Cases that depend on SpoolmanDB ``fixed`` names are deliberately excluded:
this project has no SpoolmanDB catalog to collide with.

The test only proves this module agrees with the fixture, not that the rules are right;
the rules themselves are covered in ``tests/test_spoolman_mapping.py``.
"""

import json
from pathlib import Path

import pytest

from ofd.builder.spoolman_mapping import NAME_MAX_LENGTH, shorten_long_names

CASES = json.loads(
    (Path(__file__).parent / "fixtures" / "spoolman_golden_names.json").read_text(encoding="utf-8")
)


def shortened(records: list[dict]) -> dict[str, str]:
    shorten_long_names(records)
    return {record["id"]: record["name"] for record in records}


@pytest.mark.parametrize("case", CASES, ids=[case["case"] for case in CASES])
def test_matches_reference_implementation(case):
    assert shortened(json.loads(json.dumps(case["records"]))) == case["expected"]


@pytest.mark.parametrize("case", CASES, ids=[case["case"] for case in CASES])
def test_result_does_not_depend_on_record_order(case):
    reversed_records = json.loads(json.dumps(case["records"]))[::-1]
    assert shortened(reversed_records) == case["expected"]


@pytest.mark.parametrize("case", CASES, ids=[case["case"] for case in CASES])
def test_expected_names_fit_and_are_unique(case):
    names = [(r["weight"], r["diameter"], case["expected"][r["id"]]) for r in case["records"]]
    assert all(len(name) <= NAME_MAX_LENGTH for _, _, name in names)
    assert len(set(names)) == len(names)
